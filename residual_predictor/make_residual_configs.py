"""Generate the prospectively defined 4-of-8 subset configs and manifest.

The experiment enumerates all 70 four-task subsets.  This avoids selecting
subsets after seeing their refinement gains.
"""
from itertools import combinations
import json
from pathlib import Path
import sys


TASKS = [
    "sun397",
    "stanford-cars",
    "resisc45",
    "eurosat",
    "svhn",
    "gtsrb",
    "mnist",
    "dtd",
]
MODELS = {task: f"tanganke/clip-vit-base-patch32_{task}" for task in TASKS}


def defaults_block(split: str, tasks: tuple[str, ...]) -> list[str]:
    return [
        f"  - /dataset/image_classification/{split}@{split}_datasets:",
        *[f"      - {task}" for task in tasks],
    ]


def main(repo: Path, output_root: Path) -> None:
    model_dir = repo / "config/modelpool/CLIPVisionModelPool/residual"
    task_dir = repo / "config/taskpool/CLIPVisionModelTaskPool/residual"
    model_dir.mkdir(parents=True, exist_ok=True)
    task_dir.mkdir(parents=True, exist_ok=True)
    output_root.mkdir(parents=True, exist_ok=True)

    manifest = []
    for index, tasks in enumerate(combinations(TASKS, 4)):
        subset_id = f"s4_{index:02d}"
        model_lines = [
            "# Generated by residual_predictor/make_residual_configs.py",
            "defaults:",
            *defaults_block("train", tasks),
            *defaults_block("test", tasks),
            "  - _self_",
            "_target_: fusion_bench.modelpool.CLIPVisionModelPool",
            "_recursive_: false",
            "processor: openai/clip-vit-base-patch32",
            "models:",
            "  _pretrained_: openai/clip-vit-base-patch32",
            *[f"  {task}: {MODELS[task]}" for task in tasks],
            "platform: hf",
            "",
        ]
        task_lines = [
            "# Generated by residual_predictor/make_residual_configs.py",
            "defaults:",
            "  - CLIPVisionModelTaskPool@: _template",
            "  - /dataset/image_classification/test@test_datasets:",
            *[f"      - {task}" for task in tasks],
            "",
        ]
        (model_dir / f"{subset_id}.yaml").write_text("\n".join(model_lines))
        (task_dir / f"{subset_id}.yaml").write_text("\n".join(task_lines))
        manifest.append({"index": index, "subset_id": subset_id, "tasks": list(tasks)})

    (output_root / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"generated {len(manifest)} fixed subsets")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit("usage: make_residual_configs.py REPO OUTPUT_ROOT")
    main(Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve())
